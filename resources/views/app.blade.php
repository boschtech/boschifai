    <script>
        // Applied before first paint, not in the Vue app, so there's no flash of the wrong
        // theme on load. Mirrors ThemeToggle.vue's own storage key/logic — keep both in sync
        // if either changes.
        (function () {
            var stored = localStorage.getItem('boschifai-theme');
            var prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
            if (stored === 'dark' || (stored === null && prefersDark)) {
                document.documentElement.classList.add('dark');
            }
        })();
    </script>
