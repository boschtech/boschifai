<?php

namespace Tests\Feature\Billing;

use App\Enums\RunState;
use App\Enums\RunStepStatus;
use App\Jobs\PushAndOpenPrJob;
use App\Jobs\RunCodeGenerationJob;
use App\Jobs\RunFixFailingTestsJob;
use App\Jobs\RunStandaloneActionJob;
use App\Jobs\RunTestCaseGenerationJob;
use App\Jobs\RunTestPlanJob;
use App\Models\RepoConfig;
use App\Models\Run;
use App\Services\ClaudeRunner\HeadlessClaudeInvoker;
use App\Services\Github\BranchAndCommitService;
use App\Services\Github\PullRequestService;
use App\Services\Sandbox\RunWorkspaceManager;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Queue;
use Mockery;
use PHPUnit\Framework\Attributes\DataProvider;
use Tests\TestCase;

/**
 * Every Claude-invoking job, when its step can't be paid for, leaves the run waiting for credits
 * at that step — it doesn't start Claude, doesn't mark the run failed and doesn't queue the next
 * step. (RunGapAnalysisJob is covered in EnforcedBillingTest.)
 */
class JobsAwaitingCreditsTest extends TestCase
{
    use RefreshDatabase;

    private string $checkout;

    protected function setUp(): void
    {
        parent::setUp();
        Queue::fake();
        config([
            'billing.enforce' => true,
            'billing.stage_holds_usd' => array_fill_keys(['test_plan', 'test_case_generation', 'code_generation', 'fix_failing_tests', 'push', 'build_skills', 'build_knowledge_base'], '1.00'),
            // The push step only runs Claude on the GitHub MCP path.
            'boschifai.features.github_mcp_push' => true,
            'boschifai.github_mcp.pat' => 'ghp_test',
        ]);

        $this->checkout = sys_get_temp_dir().'/boschifai-awaiting-'.uniqid();
        File::ensureDirectoryExists($this->checkout.'/.boschifai');
        $workspace = Mockery::mock(RunWorkspaceManager::class);
        $workspace->shouldReceive('path', 'prepare')->andReturn($this->checkout);
        $workspace->shouldReceive('statusPaths')->andReturn([]);
        $this->app->instance(RunWorkspaceManager::class, $workspace);

        $git = Mockery::mock(BranchAndCommitService::class);
        $git->shouldReceive('createLocalBranchAndCommit')->andReturn('boschifai/test-branch');
        $this->app->instance(BranchAndCommitService::class, $git);

        $pullRequests = Mockery::mock(PullRequestService::class);
        $pullRequests->shouldReceive('buildTitle')->andReturn('Add tests');
        $pullRequests->shouldReceive('buildBody')->andReturn('Generated by BoschifAI');
        $this->app->instance(PullRequestService::class, $pullRequests);

        $invoker = Mockery::mock(HeadlessClaudeInvoker::class)->makePartial();
        $invoker->shouldNotReceive('invoke');
        $this->app->instance(HeadlessClaudeInvoker::class, $invoker);
    }

    protected function tearDown(): void
    {
        File::deleteDirectory($this->checkout);
        parent::tearDown();
    }

    public static function jobs(): array
    {
        return [
            'test plan' => [RunTestPlanJob::class, 'test_plan', RunState::GapAnalysisRunning, []],
            'test case generation' => [RunTestCaseGenerationJob::class, 'test_case_generation', RunState::GenerationRunning, []],
            'code generation' => [RunCodeGenerationJob::class, 'code_generation', RunState::GenerationRunning, []],
            'fix failing tests' => [RunFixFailingTestsJob::class, 'fix_failing_tests', RunState::GenerationRunning, []],
            'push (GitHub MCP)' => [PushAndOpenPrJob::class, 'push', RunState::Pushing, []],
            'build skills' => [RunStandaloneActionJob::class, 'build_skills', RunState::Draft, ['run_type' => 'build_skills']],
            'build knowledge base' => [RunStandaloneActionJob::class, 'build_knowledge_base', RunState::Draft, ['run_type' => 'build_knowledge_base']],
        ];
    }

    #[DataProvider('jobs')]
    public function test_the_job_waits_for_credits_instead_of_running_or_failing(string $job, string $stepKey, RunState $startState, array $attributes): void
    {
        $repo = RepoConfig::create(['workspace_id' => $this->workspace()->id,
            'name' => 'backend', 'display_name' => 'acme/backend', 'git_remote_path' => $this->checkout,
            'base_branch' => 'main', 'github_owner' => 'acme',
        ]);
        $run = Run::create([
            'repo_config_id' => $repo->id, 'requirement_text' => 'Add a lease export', 'target_file_path' => 'app/Lease.php',
            'generated_file_path' => 'tests/Feature/LeaseExportTest.php', 'state' => $startState, ...$attributes,
        ]);

        app()->call([new $job($run->id), 'handle']);

        $run->refresh();
        $this->assertSame(RunState::AwaitingCredits, $run->state);
        $this->assertSame($stepKey, $run->awaiting_credits_step);
        $this->assertNull($run->failed_step);
        $this->assertStringStartsWith('Not enough credits: US$1.00 needed, US$0.00 available.', $run->error_message);
        $this->assertSame(RunStepStatus::Pending, $run->steps()->where('key', $stepKey)->sole()->status);
        $this->assertSame(0, $run->steps()->where('status', RunStepStatus::Running)->count(), 'No step is left looking like it is still running.');
        Queue::assertNothingPushed();
    }
}
